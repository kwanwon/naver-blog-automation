def extract_weather_location(address_str: str) -> str:
    """
    주소 문자열에서 날씨/기상청 조회에 최적화된 시/군/구(또는 읍/면/동) 명칭을 추출합니다.
    예: '강원특별자치도 양양군 양양읍 남문5길 12' -> '양양군'
    예: '인천광역시 부평구 부평대로 24' -> '부평구'
    예: '서울특별시 강남구 테헤란로 123' -> '강남구'
    예: '강원도 속초시 중앙로 10' -> '속초시'
    """
    if not address_str:
        return "서울"
    
    clean_addr = re.sub(r'\(.*?\)', '', address_str).strip()
    tokens = clean_addr.split()
    
    # 1. 시/군/구 단위 우선 탐색 (가장 날씨 예보에 정확함)
    for token in tokens:
        t = token.strip()
        if t.endswith(('시', '군', '구')) and len(t) >= 2 and not t.endswith(('특별시', '광역시', '특별자치시', '도')):
            return t

    # 2. 읍/면/동 단위 탐색
    for token in tokens:
        t = token.strip()
        if t.endswith(('읍', '면', '동')) and len(t) >= 2:
            return t

    # 3. 내장 좌표 DB에서 키워드 매칭
    for key in KOREA_DISTRICT_COORDS.keys():
        if key in clean_addr and len(key) >= 2:
            return key

    return tokens[0] if tokens else "서울"


def geocode_address(address_str: str) -> Optional[Tuple[float, float, str]]:
    """
    주소 문자열을 위도(latitude), 경도(longitude), 정제된 지역명으로 변환합니다.
    외부 라이브러리(geopy) 없이 동작하며, 3단계 다중 폴백 시스템을 사용합니다:
    1단계: OpenStreetMap Nominatim REST API (경량 웹 요청, SSL/타임아웃 안전 처리)
    2단계: 주소 정제 후 재검색 (번지/건물명 제외한 도로명/동 단위)
    3단계: 내장된 전국 200+개 시/군/구 정밀 좌표 사전 매칭
    
    Returns:
        (latitude, longitude, display_or_district_name) 또는 None
    """
    if not address_str:
        return None

    raw_addr = address_str.strip()
    # 괄호 및 층/호수 등 상세 부가정보 제거
    clean_addr = re.sub(r'\(.*?\)', '', raw_addr).strip()
    clean_addr = re.sub(r'\s+[0-9]+층.*$', '', clean_addr).strip()
    clean_addr = re.sub(r'\s+[0-9]+호.*$', '', clean_addr).strip()

    search_queries = [clean_addr]
    
    # 도로명+건물번호 추출 (예: '강원도 양양군 양양읍 남문5길 12 2층' -> '양양군 양양읍 남문5길 12')
    match_road = re.search(r'([가-힣]+[시|군|구]\s+[가-힣]+[읍|면|동|리|로|길]\s+[가-힣0-9\-]+[로|길]?\s*[0-9\-]+)', clean_addr)
    if match_road:
        search_queries.append(match_road.group(1).strip())
        
    # 시/군/구 + 읍/면/동 추출
    match_dong = re.search(r'([가-힣]+[시|군|구]\s+[가-힣0-9]+[읍|면|동|리|로|길])', clean_addr)
    if match_dong:
        search_queries.append(match_dong.group(1).strip())

    # 1 & 2단계: OpenStreetMap REST API 호출 (geopy 패키지 불필요)
    ctx = ssl._create_unverified_context()
    for query in search_queries:
        if not query:
            continue
        try:
            encoded_query = urllib.parse.quote(query)
            api_url = f"https://nominatim.openstreetmap.org/search?q={encoded_query}&format=json&limit=1&addressdetails=1"
            req = urllib.request.Request(
                api_url,
                headers={
                    'User-Agent': 'LionGymAutoPoster/1.2 (Mozilla/5.0 Windows NT 10.0; Win64; x64)',
                    'Accept-Language': 'ko-KR,ko;q=0.9'
                }
            )
            with urllib.request.urlopen(req, timeout=4, context=ctx) as response:
                if response.status == 200:
                    resp_data = json.loads(response.read().decode('utf-8'))
                    if resp_data and len(resp_data) > 0:
                        first_item = resp_data[0]
                        lat = float(first_item.get('lat', 0))
                        lon = float(first_item.get('lon', 0))
                        display_name = first_item.get('display_name', query)
                        if lat > 0 and lon > 0:
                            return (lat, lon, display_name)
        except Exception:
            # 네트워크 타임아웃이나 차단 시 다음 쿼리 또는 3단계 내장 사전으로 자연스럽게 진행
            pass

    # 3단계: 내장 전국 시/군/구 정밀 좌표 사전 매칭 (네트워크 오류 완벽 방어)
    extracted_loc = extract_weather_location(clean_addr)
    if extracted_loc in KOREA_DISTRICT_COORDS:
        lat, lon = KOREA_DISTRICT_COORDS[extracted_loc]
        return (lat, lon, extracted_loc)

    # 전체 주소 내 토큰 매칭
    for token in reversed(clean_addr.split()):
        t = token.strip()
        if t in KOREA_DISTRICT_COORDS:
            lat, lon = KOREA_DISTRICT_COORDS[t]
            return (lat, lon, t)

    for key, (lat, lon) in KOREA_DISTRICT_COORDS.items():
        if key in clean_addr and len(key) >= 2:
            return (lat, lon, key)

    return None
